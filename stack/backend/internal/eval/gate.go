package eval

import (
	"encoding/json"
	"fmt"
	"os"
)

// GateBaseline is the committed floor for the local check-worthiness gate
// (VER-225). The fixture records, for every golden statement, the shipped
// artifact's calibrated score and the generative gate's verdict under the
// production prompt; this baseline gates what those recordings must satisfy
// at the recorded band. It is an additive key in baseline.json: a baseline
// without it skips the gate entirely, so older eval flows are untouched.
type GateBaseline struct {
	// MinCascadeAccuracy floors the accuracy of the full cascade decision
	// (local outside the band, recorded generative verdict inside it) against
	// the human labels - the "overall gate accuracy does not regress" check.
	MinCascadeAccuracy float64 `json:"min_cascade_accuracy"`
	// MinOutsideBandLLMAgreement floors how often a local decision outside
	// the band matches the generative gate's recorded verdict.
	MinOutsideBandLLMAgreement float64 `json:"min_outside_band_llm_agreement"`
	// MaxLLMCallRate caps the fraction of statements whose score falls inside
	// the band and would still be routed to the generative gate.
	MaxLLMCallRate float64 `json:"max_llm_call_rate"`
}

// GateCase is one golden statement with its recorded artifact score and the
// recorded generative-gate verdict.
type GateCase struct {
	Text  string `json:"text"`
	Label string `json:"label"`
	// Score is the shipped (INT8) artifact's calibrated probability.
	Score float64 `json:"score"`
	// ScoreFP32 is the fp32 reference export's probability, reported so a
	// quantization drift is visible in review; it is not gated.
	ScoreFP32 float64 `json:"score_fp32"`
	// LLMGate is the generative gate's recorded verdict under the production
	// French prompt.
	LLMGate bool `json:"llm_gate"`
}

// GateGolden is the committed gate fixture, regenerated by the training
// pipeline (stack/ml/checkworthy) on every retrain and never edited by hand.
type GateGolden struct {
	About    string     `json:"_about"`
	BandLow  float64    `json:"band_low"`
	BandHigh float64    `json:"band_high"`
	Cases    []GateCase `json:"cases"`
}

// LoadGateGolden reads and validates the gate fixture: a malformed label, a
// score outside [0, 1], or an inverted band is a hard error, never a gate
// that passes vacuously.
func LoadGateGolden(path string) (GateGolden, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return GateGolden{}, fmt.Errorf("eval: read gate golden: %w", err)
	}
	var g GateGolden
	if err := json.Unmarshal(raw, &g); err != nil {
		return GateGolden{}, fmt.Errorf("eval: decode gate golden: %w", err)
	}
	if len(g.Cases) == 0 {
		return GateGolden{}, fmt.Errorf("eval: gate golden %s has no cases", path)
	}
	if g.BandLow < 0 || g.BandHigh > 1 || g.BandLow > g.BandHigh {
		return GateGolden{}, fmt.Errorf("eval: gate golden band [%v, %v) is not a probability band", g.BandLow, g.BandHigh)
	}
	for i, c := range g.Cases {
		if c.Label != "claim" && c.Label != "not_claim" {
			return GateGolden{}, fmt.Errorf("eval: gate golden case %d has unknown label %q", i, c.Label)
		}
		if c.Score < 0 || c.Score > 1 {
			return GateGolden{}, fmt.Errorf("eval: gate golden case %d score %v outside [0, 1]", i, c.Score)
		}
	}
	return g, nil
}

// GateReport is the recomputed gate metrics at the fixture's recorded band.
type GateReport struct {
	Cases                   int
	OutsideBand             int
	InBand                  int
	CascadeAccuracy         float64
	LLMAccuracy             float64
	OutsideBandAccuracy     float64
	OutsideBandLLMAgreement float64
	LLMCallRate             float64
}

// RunGate replays the recorded scores through the band routing: a score below
// the band rejects locally, at or above its upper bound accepts locally, and
// anything inside defers to the recorded generative verdict. Everything is
// recomputed from the fixture, so the gate needs no model, network, or
// database.
func RunGate(g GateGolden) GateReport {
	rep := GateReport{Cases: len(g.Cases)}
	cascadeCorrect, llmCorrect, outsideCorrect, outsideAgree := 0, 0, 0, 0
	for _, c := range g.Cases {
		labelClaim := c.Label == "claim"
		if c.LLMGate == labelClaim {
			llmCorrect++
		}
		inBand := c.Score >= g.BandLow && c.Score < g.BandHigh
		if inBand {
			rep.InBand++
			if c.LLMGate == labelClaim {
				cascadeCorrect++
			}
			continue
		}
		rep.OutsideBand++
		decision := c.Score >= g.BandHigh
		if decision == labelClaim {
			outsideCorrect++
			cascadeCorrect++
		}
		if decision == c.LLMGate {
			outsideAgree++
		}
	}
	rep.CascadeAccuracy = float64(cascadeCorrect) / float64(rep.Cases)
	rep.LLMAccuracy = float64(llmCorrect) / float64(rep.Cases)
	rep.LLMCallRate = float64(rep.InBand) / float64(rep.Cases)
	if rep.OutsideBand > 0 {
		rep.OutsideBandAccuracy = float64(outsideCorrect) / float64(rep.OutsideBand)
		rep.OutsideBandLLMAgreement = float64(outsideAgree) / float64(rep.OutsideBand)
	} else {
		rep.OutsideBandAccuracy = 1
		rep.OutsideBandLLMAgreement = 1
	}
	return rep
}

// Format renders the gate report for the eval command output.
func (r GateReport) Format() string {
	return fmt.Sprintf(
		"check-worthiness gate: %d cases, %d decided locally, %d routed to the model\n"+
			"  cascade accuracy          %.3f (generative gate alone %.3f)\n"+
			"  outside-band accuracy     %.3f\n"+
			"  outside-band agreement    %.3f\n"+
			"  model call rate           %.3f",
		r.Cases, r.OutsideBand, r.InBand,
		r.CascadeAccuracy, r.LLMAccuracy,
		r.OutsideBandAccuracy,
		r.OutsideBandLLMAgreement,
		r.LLMCallRate,
	)
}

// CheckGate compares a gate report against the baseline's gate floors and
// returns the misses in a stable order. A nil receiver section means the
// baseline does not gate the local classifier yet.
func (b Baseline) CheckGate(r GateReport) []RetrievalFailure {
	if b.Gate == nil {
		return nil
	}
	var failures []RetrievalFailure
	if lt(r.CascadeAccuracy, b.Gate.MinCascadeAccuracy) {
		failures = append(failures, RetrievalFailure{Category: "cascade-accuracy", Got: r.CascadeAccuracy, Want: b.Gate.MinCascadeAccuracy})
	}
	if lt(r.OutsideBandLLMAgreement, b.Gate.MinOutsideBandLLMAgreement) {
		failures = append(failures, RetrievalFailure{Category: "llm-agreement", Got: r.OutsideBandLLMAgreement, Want: b.Gate.MinOutsideBandLLMAgreement})
	}
	if lt(b.Gate.MaxLLMCallRate, r.LLMCallRate) {
		failures = append(failures, RetrievalFailure{Category: "llm-call-rate", Got: r.LLMCallRate, Want: b.Gate.MaxLLMCallRate})
	}
	return failures
}
