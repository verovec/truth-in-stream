package eval

import (
	"encoding/json"
	"fmt"
	"os"
)

// NLIBaseline is the committed floor for the local NLI stance stage
// (VER-228). The fixture records every golden case's per-passage calibrated
// stance probabilities from the shipped artifact; this baseline gates what
// replaying the consensus rule over those recordings must satisfy. It is an
// additive key in baseline.json: a baseline without it skips the check.
type NLIBaseline struct {
	// MinDecidedAccuracy floors the accuracy of locally-decided verdicts
	// against the case labels - a wrong local verdict is worse than an
	// escalation, so this floor is strict.
	MinDecidedAccuracy float64 `json:"min_decided_accuracy"`
	// MinLocalShare floors the fraction of cases decided locally - the
	// stage's reason to exist is removing generative calls, so a collapse in
	// coverage is a regression even at perfect accuracy.
	MinLocalShare float64 `json:"min_local_share"`
}

// NLICase is one golden claim with the recorded stance of each of its
// passages. Probs rows are [entailment, neutral, contradiction] and align
// with PassageIDs.
type NLICase struct {
	ID         string      `json:"id"`
	Claim      string      `json:"claim"`
	Label      string      `json:"label"`
	NegationOf string      `json:"negation_of"`
	PassageIDs []string    `json:"passage_ids"`
	Probs      [][]float64 `json:"probs"`
}

// NLIGolden is the committed stance fixture, regenerated by the training
// pipeline's nli-calibrate step and never edited by hand. The thresholds and
// agreement count recorded here are the shipped configuration defaults, so
// the eval replays exactly what production would decide.
type NLIGolden struct {
	About               string    `json:"_about"`
	Temperature         float64   `json:"temperature"`
	EntailThreshold     float64   `json:"entail_threshold"`
	ContradictThreshold float64   `json:"contradict_threshold"`
	MinAgree            int       `json:"min_agree"`
	Cases               []NLICase `json:"cases"`
}

// LoadNLIGolden reads and validates the stance fixture: an unknown label, a
// probability outside [0, 1], a malformed row, or a dangling negation link is
// a hard error, never a gate that passes vacuously.
func LoadNLIGolden(path string) (NLIGolden, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return NLIGolden{}, fmt.Errorf("eval: read nli golden: %w", err)
	}
	var g NLIGolden
	if err := json.Unmarshal(raw, &g); err != nil {
		return NLIGolden{}, fmt.Errorf("eval: decode nli golden: %w", err)
	}
	if len(g.Cases) == 0 {
		return NLIGolden{}, fmt.Errorf("eval: nli golden %s has no cases", path)
	}
	if !(g.EntailThreshold > 0 && g.EntailThreshold <= 1) || !(g.ContradictThreshold > 0 && g.ContradictThreshold <= 1) {
		return NLIGolden{}, fmt.Errorf("eval: nli golden thresholds must be probabilities in (0, 1], got entail %v contradict %v", g.EntailThreshold, g.ContradictThreshold)
	}
	if g.MinAgree < 1 {
		return NLIGolden{}, fmt.Errorf("eval: nli golden min agree must be at least 1, got %d", g.MinAgree)
	}
	ids := make(map[string]bool, len(g.Cases))
	for i, c := range g.Cases {
		if c.Label != "support" && c.Label != "refute" && c.Label != "neutral" {
			return NLIGolden{}, fmt.Errorf("eval: nli golden case %d has unknown label %q", i, c.Label)
		}
		if len(c.Probs) == 0 || len(c.Probs) != len(c.PassageIDs) {
			return NLIGolden{}, fmt.Errorf("eval: nli golden case %q has %d prob rows for %d passages", c.ID, len(c.Probs), len(c.PassageIDs))
		}
		for _, row := range c.Probs {
			if len(row) != 3 {
				return NLIGolden{}, fmt.Errorf("eval: nli golden case %q has a %d-wide prob row, want 3", c.ID, len(row))
			}
			for _, p := range row {
				if p < 0 || p > 1 {
					return NLIGolden{}, fmt.Errorf("eval: nli golden case %q probability %v outside [0, 1]", c.ID, p)
				}
			}
		}
		if ids[c.ID] {
			return NLIGolden{}, fmt.Errorf("eval: nli golden duplicate case id %q", c.ID)
		}
		ids[c.ID] = true
	}
	for _, c := range g.Cases {
		if c.NegationOf != "" && !ids[c.NegationOf] {
			return NLIGolden{}, fmt.Errorf("eval: nli golden case %q negation_of unknown case %q", c.ID, c.NegationOf)
		}
	}
	return g, nil
}

// nliDecide replays the production consensus rule over one case's recorded
// probabilities: support only when at least minAgree passages entail above
// threshold and none contradicts above its own, refute symmetrically,
// escalate otherwise. Kept in lockstep with the service stage and the
// pipeline's decide().
func nliDecide(probs [][]float64, entailThreshold, contradictThreshold float64, minAgree int) string {
	entails, contradicts := 0, 0
	for _, row := range probs {
		if row[0] >= entailThreshold {
			entails++
		}
		if row[2] >= contradictThreshold {
			contradicts++
		}
	}
	switch {
	case entails >= minAgree && contradicts == 0:
		return "support"
	case contradicts >= minAgree && entails == 0:
		return "refute"
	default:
		return "escalate"
	}
}

// NLIReport is the replayed stance metrics at the fixture's recorded
// thresholds.
type NLIReport struct {
	Cases              int
	Decided            int
	LocalShare         float64
	DecidedAccuracy    float64
	NegationViolations []string
	Wrong              []string
}

// RunNLI replays every case and the negation controls. Everything is
// recomputed from the fixture, so the check needs no model, network, or
// database.
func RunNLI(g NLIGolden) NLIReport {
	rep := NLIReport{Cases: len(g.Cases)}
	decisions := make(map[string]string, len(g.Cases))
	correct := 0
	for _, c := range g.Cases {
		decision := nliDecide(c.Probs, g.EntailThreshold, g.ContradictThreshold, g.MinAgree)
		decisions[c.ID] = decision
		if decision == "escalate" {
			continue
		}
		rep.Decided++
		if decision == c.Label {
			correct++
		} else {
			rep.Wrong = append(rep.Wrong, fmt.Sprintf("%s: decided %s, labeled %s", c.ID, decision, c.Label))
		}
	}
	rep.LocalShare = float64(rep.Decided) / float64(rep.Cases)
	if rep.Decided > 0 {
		rep.DecidedAccuracy = float64(correct) / float64(rep.Decided)
	} else {
		rep.DecidedAccuracy = 1
	}
	for _, c := range g.Cases {
		if c.NegationOf == "" {
			continue
		}
		mine, theirs := decisions[c.ID], decisions[c.NegationOf]
		if mine != "escalate" && mine == theirs {
			rep.NegationViolations = append(rep.NegationViolations, fmt.Sprintf("%s and its negation %s both decided %s", c.ID, c.NegationOf, mine))
		}
	}
	return rep
}

// Format renders the stance report for the eval command output.
func (r NLIReport) Format() string {
	out := fmt.Sprintf(
		"nli stance stage: %d cases, %d decided locally (share %.3f)\n"+
			"  decided accuracy          %.3f\n"+
			"  negation violations       %d",
		r.Cases, r.Decided, r.LocalShare, r.DecidedAccuracy, len(r.NegationViolations))
	for _, v := range r.NegationViolations {
		out += "\n    " + v
	}
	for _, w := range r.Wrong {
		out += "\n  wrong: " + w
	}
	return out
}

// CheckNLI compares a stance report against the baseline's floors and the
// hard negation invariant, returning the misses in a stable order. A nil
// receiver section means the baseline does not gate the stance stage yet.
func (b Baseline) CheckNLI(r NLIReport) []GateFailure {
	if b.NLI == nil {
		return nil
	}
	var failures []GateFailure
	if lt(r.DecidedAccuracy, b.NLI.MinDecidedAccuracy) {
		failures = append(failures, GateFailure{Metric: "nli-decided-accuracy", Got: r.DecidedAccuracy, Want: b.NLI.MinDecidedAccuracy})
	}
	if lt(r.LocalShare, b.NLI.MinLocalShare) {
		failures = append(failures, GateFailure{Metric: "nli-local-share", Got: r.LocalShare, Want: b.NLI.MinLocalShare})
	}
	if len(r.NegationViolations) > 0 {
		failures = append(failures, GateFailure{Metric: "nli-negation-violations", Got: float64(len(r.NegationViolations)), Want: 0, Ceiling: true})
	}
	return failures
}
